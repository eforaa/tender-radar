// Legal reference layer: what each state risk indicator points at in
// procurement law, and which criminal-law articles an investigator would
// normally examine next.
//
// Nothing here qualifies anyone's conduct. An indicator firing is a reason to
// request the documents, not a finding. Intent and knowing falsity are decided
// by a court on evidence, never by a rule in this file.
//
// Provenance is tracked deliberately. Where the state publishes the norm
// itself (the `legitimateness` field of the indicator), that text is shown as
// the state's own citation. Where it does not — six of the fourteen — the norm
// below is our reading, labelled as such, and justified by the indicator's own
// description.

export type NormSource = "state" | "reading";

